_FLOW_TEST_KEYS = frozenset({"kind", "id", "source", "flow", "input", "expectStatus", "expectOutput"})
_OPERATOR_TEST_KEYS = frozenset({"kind", "id", "source", "operator", "cases"})
_CASE_KEYS = frozenset({"input", "expectAccepted", "expectOutput"})


def _validate_tests(tests):
    """Structural validation of project-declared regression tests.

    Every entry must declare the origin of its expectations (`source`) — the
    landing point of the design rule "AI-generated test expectations must cite
    a business rule or a confirmed sample".
    """
    if not isinstance(tests, list):
        raise ContractError("INVALID_TEST_CONFIG", "tests must be a list")
    seen_ids = set()
    for entry in tests:
        if not isinstance(entry, dict):
            raise ContractError("INVALID_TEST_CONFIG", "Test entry must be an object")
        kind = entry.get("kind")
        if kind not in ("flow", "operator"):
            raise ContractError("INVALID_TEST_CONFIG", 'Test kind must be "flow" or "operator"', kind)
        test_id = entry.get("id")
        if type(test_id) is not str or not test_id:
            raise ContractError("INVALID_TEST_CONFIG", "Test id must be a nonempty string")
        if test_id in seen_ids:
            raise ContractError("INVALID_TEST_CONFIG", "Duplicate test id", test_id)
        seen_ids.add(test_id)
        source = entry.get("source")
        if type(source) is not str or not source.strip():
            raise ContractError("INVALID_TEST_CONFIG",
                                "Test expectations must declare their origin (business rule or confirmed sample)",
                                f"{test_id}.source")
        if kind == "flow":
            if set(entry) - _FLOW_TEST_KEYS:
                raise ContractError("INVALID_TEST_CONFIG", "Unknown field in flow test", sorted(set(entry) - _FLOW_TEST_KEYS)[0])
            if type(entry.get("flow")) is not str or not entry["flow"]:
                raise ContractError("INVALID_TEST_CONFIG", "Flow test requires a flow id", test_id)
            if not isinstance(entry.get("input"), dict):
                raise ContractError("INVALID_TEST_CONFIG", "Flow test input must be an object", test_id)
            status = entry.get("expectStatus", "SUCCEEDED")
            if type(status) is not str or not status:
                raise ContractError("INVALID_TEST_CONFIG", "expectStatus must be a nonempty string", test_id)
            _validate_expect_output(entry.get("expectOutput"), test_id)
        else:
            if set(entry) - _OPERATOR_TEST_KEYS:
                raise ContractError("INVALID_TEST_CONFIG", "Unknown field in operator test", sorted(set(entry) - _OPERATOR_TEST_KEYS)[0])
            ref = entry.get("operator")
            if type(ref) is not str or ref.count("@") != 1 or not all(ref.split("@")):
                raise ContractError("INVALID_TEST_CONFIG", "Operator test requires a ref in name@version form", test_id)
            cases = entry.get("cases")
            if not isinstance(cases, list) or not cases:
                raise ContractError("INVALID_TEST_CONFIG", "Operator test cases must be a nonempty list", test_id)
            for case in cases:
                if not isinstance(case, dict) or set(case) - _CASE_KEYS:
                    raise ContractError("INVALID_TEST_CONFIG", "Case must be an object with input/expectAccepted/expectOutput",
                                        test_id)
                if not isinstance(case.get("input"), dict):
                    raise ContractError("INVALID_TEST_CONFIG", "Case input must be an object", test_id)
                accepted = case.get("expectAccepted", True)
                if type(accepted) is not bool:
                    raise ContractError("INVALID_TEST_CONFIG", "expectAccepted must be a boolean", test_id)
                _validate_expect_output(case.get("expectOutput"), test_id)


def _validate_expect_output(expect_output, test_id):
    if expect_output is None:
        return
    if not isinstance(expect_output, dict):
        raise ContractError("INVALID_TEST_CONFIG", "expectOutput must map point paths to expected values", test_id)
    for path in expect_output:
        if type(path) is not str or not path:
            raise ContractError("INVALID_TEST_CONFIG", "expectOutput paths must be nonempty point paths", test_id)


def _read_project_with_tests(path):
    """Load a project configuration and compile it, returning (tests, release)."""
    text = path.read_text(encoding="utf-8")
    config = parse_project(text) if path.suffix == ".mf" else load_json(text)
    if not isinstance(config, dict) or set(config) - {"modules", "flows", "defaults", "tests"}:
        raise ContractError("INVALID_PROJECT", "Expected modules, flows and optional defaults and tests")
    if not isinstance(config.get("modules"), list) or any(type(p) is not str for p in config["modules"]):
        raise ContractError("INVALID_PROJECT", "modules must list trusted Python file paths")
    if not isinstance(config.get("flows"), list) or not config["flows"]:
        raise ContractError("INVALID_PROJECT", "flows must be a nonempty list")
    defaults = config.get("defaults", {})
    if not isinstance(defaults, dict):
        raise ContractError("INVALID_PROJECT", "defaults must be an object")
    validate_policy(defaults)
    tests = config.get("tests", [])
    _validate_tests(tests)
    # --ephemeral is explicit at the command boundary and changes only defaults;
    # a node that asks for durability remains invalid without a real provider.
    defaults = {**defaults, "durability": "ephemeral", "recovery": {"enabled": False}}
    registry = discover([path.parent / p for p in config["modules"]])
    release = compile_release(registry, config["flows"], defaults=defaults, source_file=str(path.resolve()))
    return tests, release


def _read_project(path):
    return _read_project_with_tests(path)[1]


def _load_project(path):
    try:
        return _read_project(path)
    except MicroFlowError as exc:
        exc.diagnostic = replace(exc.diagnostic, source_file=exc.diagnostic.source_file or str(path.resolve()))
        raise


_BOUNDARIES = (
    "Local runtime executes operator, subflow and join nodes only; "
    "route/map/loop/wait raise UNSUPPORTED_LOCAL_NODE.",
    "Durability, recovery, idempotency, cache, retry and resource policies are "
    "rejected by the local runner (UNSUPPORTED_LOCAL_POLICY).",
    "Write-effect operators require an explicit allow_write runner "
    "(WRITE_EFFECT_NOT_ALLOWED); scheduled execution refuses write attempts.",
    "Calling success is not business success: outputs must satisfy the declared schema.",
)


def _context(args):
    release = _load_project(args.project)
    index = build_index(release)
    if args.ref not in release.registry.operators:
        raise ContractError("UNKNOWN_OPERATOR", "Operator is not registered in this release", args.ref)
    op = release.registry.operators[args.ref]
    references = operator_references(index, args.ref)
    using = operator_flows(index, args.ref)
    upstream = tuple(sorted({u for flow_id in using for u in upstream_flows(index, flow_id)}))
    if args.budget < 1:
        raise ContractError("CONTEXT_BUDGET_EXCEEDED", "Budget must be a positive integer", "--budget")
    related, skipped, notes = [], [], []
    tests_dir = args.tests_dir
    if tests_dir is None:
        default_dir = args.project.parent / "tests"
        tests_dir = default_dir if default_dir.is_dir() else None
    if tests_dir is None:
        notes.append("no test directory located; pass --tests-dir explicitly")
    else:
        name = args.ref.split("@", 1)[0]
        for path in sorted(tests_dir.rglob("*.py")):
            if path.stat().st_size > 1_000_000:
                skipped.append(str(path))
                continue
            count = path.read_text(encoding="utf-8", errors="replace").count(name)
            if count:
                related.append({"path": str(path), "matches": count})
        if len(related) > args.budget:
            raise ContractError("CONTEXT_BUDGET_EXCEEDED", "Related test files exceed the context budget",
                                str(tests_dir), hint="Narrow --tests-dir or raise --budget.")
    boundaries = list(_BOUNDARIES)
    if op.capabilities.get("effect") == "write":
        boundaries.append("This operator declares write; until a confirmation-capable runtime "
                          "accepts it, scheduled execution refuses the attempt.")
    raw_doc = inspect.getdoc(op.method) or ""
    docstring, truncated = (raw_doc[:2000], True) if len(raw_doc) > 2000 else (raw_doc, False)
    return {"protocol": "microflow-cli-v1", "releaseId": release.release_id, "durability": "ephemeral",
            "context": {
                "operator": {"ref": op.ref, "description": op.description,
                             "inputSchema": op.input_schema, "outputSchema": op.output_schema,
                             "capabilities": thaw(op.capabilities),
                             "fallbackCapabilities": thaw(op.fallback_capabilities),
                             "defaultPolicy": thaw(op.default_policy), "sourceFile": op.source_file,
                             "handlers": {role: getattr(getattr(op, role), "__qualname__", None)
                                          for role in ("method", "fallback", "metrix", "log")}},
                "summary": {"docstring": docstring, "truncated": truncated},
                "references": describe_references(references), "flows": list(using),
                "upstreamFlows": list(upstream),
                "relatedTests": related, "skippedOversizeTestFiles": skipped, "notes": notes,
                "boundaries": boundaries}}


def _scaffold(args):
    if args.kind == "operator":
        return _scaffold_operator(args)
    return _scaffold_flow(args)


def _scaffold_operator(args):
    name, version = args.name, args.version
    if not _SCAFFOLD_ID.match(name or ""):
        raise ContractError("INVALID_SCAFFOLD_ID", "Scaffold name must be filename-safe", name)
    if not version or "@" in version:
        raise ContractError("INVALID_OPERATOR_ID", "Invalid scaffold version", version)
    proxies = [item for item in (args.proxy or "").split(",") if item]
    if sorted(set(proxies)) != sorted(proxies) or set(proxies) - {"metrix", "log"}:
        raise ContractError("INVALID_SCAFFOLD_ID", "Proxies support metrix and log only", args.proxy)
    into = args.into
    if into.exists() and not into.is_dir():
        raise ContractError("SCAFFOLD_TARGET_EXISTS", "Target is not a directory", str(into))
    targets = [(into / f"{name}_operator.py", "operator"), (into / f"test_{name}_operator.py", "test")]
    for path, _ in targets:
        if path.exists():
            raise ContractError("SCAFFOLD_TARGET_EXISTS", "Scaffold never overwrites", str(path))
    into.mkdir(parents=True, exist_ok=True)
    fallback = _FALLBACK_SNIPPET.replace("@@NAME@@", name) if args.with_fallback else ""
    extra = _OPERATOR_EXTRA_FALLBACK.replace("@@NAME@@", name) if args.with_fallback else ""
    proxies_text = "".join((_METRIX_PROXY_SNIPPET if role == "metrix" else _LOG_PROXY_SNIPPET)
                           .replace("@@NAME@@", name) for role in proxies)
    module_text = (_OPERATOR_TEMPLATE.replace("@@TITLE@@", name).replace("@@NAME@@", name)
                   .replace("@@VERSION@@", version).replace("@@FALLBACK@@", fallback)
                   .replace("@@PROXIES@@", proxies_text).replace("@@EXTRA@@", extra))
    test_text = (_TEST_TEMPLATE.replace("@@REF@@", f"{name}@{version}").replace("@@NAME@@", name)
                 .replace("@@TEST_MODULE@@", f"test_{name}_operator")
                 .replace("@@CLASS@@", name.title().replace("_", "").replace("-", "") + "ContractTests"))
    written = []
    for (path, kind), content in zip(targets, (module_text, test_text)):
        path.write_text(content, encoding="utf-8")
        written.append({"path": str(path), "kind": kind})
    return {"protocol": "microflow-cli-v1", "into": str(into), "files": written, "nextSteps": [
        "Fill the [fill] sections and declare effect truthfully; a write effect is refused until the host confirms.",
        "List the module under a project configuration's modules, then: microflow check <project> --ephemeral",
    ]}


def _scaffold_flow(args):
    if not _SCAFFOLD_ID.match(args.flow_id or ""):
        raise ContractError("INVALID_SCAFFOLD_ID", "Scaffold flow id must be filename-safe", args.flow_id)
    if not args.input_schema or not args.output_schema:
        raise ContractError("UNKNOWN_SCHEMA", "Scaffold flow needs both schema names", args.flow_id)
    parts = args.operator.split("@")
    if len(parts) != 2 or not all(parts):
        raise ContractError("INVALID_OPERATOR_ID", "Operator ref must be name@version", args.operator)
    flow = {"id": args.flow_id, "input_schema": args.input_schema, "output_schema": args.output_schema,
            "nodes": {"step": {"type": "operator", "operator": args.operator}},
            "outputs": {"result": {"from": "nodes.step.output.data"}}}
    project = {"modules": list(args.module), "flows": [flow]}
    into = args.into
    if into.exists() and not into.is_dir():
        raise ContractError("SCAFFOLD_TARGET_EXISTS", "Target is not a directory", str(into))
    target = into / f"{args.flow_id}.flow.json"
    if target.exists():
        raise ContractError("SCAFFOLD_TARGET_EXISTS", "Scaffold never overwrites", str(target))
    into.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(project, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return {"protocol": "microflow-cli-v1", "into": str(into),
            "files": [{"path": str(target), "kind": "project"}], "nextSteps": [
        "Ensure the referenced schemas and operator module are registered under modules; "
        "module paths resolve relative to this file.",
        "Align the node input and flow output mappings with the real schemas, then: "
        "microflow check <this file> --ephemeral",
    ]}


def _canonical(value):
    return json.dumps(value, ensure_ascii=True, sort_keys=True)


def _compare_expect_output(expect_output, data):
    """Point-path expectations vs output data; returns a failure detail or None.

    Comparison is canonical-JSON equality: type-strict (bool is not int) and
    order-sensitive inside arrays; a missing path can never equal an expected
    value (区分缺失与 null，与框架路径语义一致).
    """
    for path in sorted(expect_output):
        actual = get_path(data, path, default=MISSING)
        if actual is MISSING or _canonical(actual) != _canonical(expect_output[path]):
            return {"path": path, "expected": expect_output[path],
                    "actual": None if actual is MISSING else actual,
                    "present": actual is not MISSING}
    return None


def _case_result(test_id, kind, name, failures):
    return {"id": test_id, "kind": kind, "name": name,
            "status": "failed" if failures else "passed",
            **({"failures": failures} if failures else {})}


def _run_flow_case(release, test):
    flow_id = test["flow"]
    if flow_id not in release.flows:
        raise ContractError("UNKNOWN_TEST_TARGET", "Flow test references an unknown flow",
                            f'{test["id"]}: {flow_id}')
    outcome = LocalRuntime(release).run(flow_id, test["input"])
    status = outcome.output["meta"]["status"]
    expected_status = test.get("expectStatus", "SUCCEEDED")
    failures = []
    if status != expected_status:
        failures.append({"reason": "status-mismatch", "expected": expected_status, "actual": status})
    mismatch = _compare_expect_output(test.get("expectOutput", {}), outcome.output["data"])
    if mismatch is not None:
        failures.append({"reason": "output-mismatch", **mismatch})
    return _case_result(test["id"], "flow", flow_id, failures)


def _run_operator_cases(release, test):
    ref = test["operator"]
    if ref not in release.registry.operators:
        raise ContractError("UNKNOWN_TEST_TARGET", "Operator test references an unknown ref",
                            f'{test["id"]}: {ref}')
    operator = release.registry.operators[ref]
    schema = release.registry.schemas[operator.output_schema]
    results = []
    for index, case in enumerate(test["cases"], start=1):
        name = f"{ref}#{index}"
        failures = []
        output = Output()
        try:
            accepted = operator.method(Input(case["input"]), output, Context({}, {}),
                                       Metrics(), Debug(threading.Event()), Log())
        except Exception as exc:  # contract test: the case executed and failed
            failures.append({"reason": "exception", "error": type(exc).__name__, "message": str(exc)[:500]})
        else:
            expected_accepted = case.get("expectAccepted", True)
            if bool(accepted) is not expected_accepted:
                failures.append({"reason": "accepted-mismatch",
                                 "expected": expected_accepted, "actual": bool(accepted)})
            if accepted and expected_accepted:
                try:
                    validate_schema(output.data, schema, "output.data")
                except MicroFlowError as exc:
                    failures.append({"reason": "schema-violation", "detail": exc.diagnostic.error_code,
                                     "message": exc.diagnostic.message})
                mismatch = _compare_expect_output(case.get("expectOutput", {}), output.data)
                if mismatch is not None:
                    failures.append({"reason": "output-mismatch", **mismatch})
        results.append(_case_result(test["id"], "operator", name, failures))
    return results


def _test(args):
    tests, release = _read_project_with_tests(args.project)
    if args.budget < 1:
        raise ContractError("TEST_BUDGET_EXCEEDED", "Budget must be a positive integer", "--budget")
    cases = []
    for test in tests:
        if test["kind"] == "flow":
            cases.append(_run_flow_case(release, test))
        else:
            cases.extend(_run_operator_cases(release, test))
    if len(cases) > args.budget:
        raise ContractError("TEST_BUDGET_EXCEEDED", "Test cases exceed the explicit budget", str(args.budget))
    passed = sum(1 for case in cases if case["status"] == "passed")
    return {"protocol": "microflow-cli-v1", "releaseId": release.release_id, "durability": "ephemeral",
            "tests": {"total": len(cases), "passed": passed, "failed": len(cases) - passed},
            "cases": cases}


